function repairI18nDictionary(dictionary) {
  if (!window.ToxStore?.repairText) return;
  Object.values(dictionary).forEach((messages) => {
    Object.keys(messages).forEach((key) => {
      messages[key] = ToxStore.repairText(messages[key]);
    });
  });
}

