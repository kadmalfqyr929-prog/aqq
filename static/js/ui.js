function renderInventoryRows(target, state) {
  if (!target) return;
  target.innerHTML = state.products
    .map((product) => {
      const isLow = Number(product.stockQuantity || 0) <= ToxStore.thresholdQuantity(product);
      const expired = state.alerts.some((alert) => alert.type === "EXPIRED_PRODUCT" && alert.productId === product.id);
      const out = state.alerts.some((alert) => alert.type === "OUT_OF_STOCK" && alert.productId === product.id);
      const unitMatrix = product.units.map((unit) => `${localizedUnitName(unit, state.lang)} x${Number(unit.multiplier)}`).join(" / ");
      return `
        <tr class="${isLow || expired ? "low-stock" : ""}">
          <td><strong>${product.name}</strong><br><small>${ToxStore.productBaseUnit(product)}</small></td>
          <td>${ToxStore.getWarehouseName(product.warehouseId)}</td>
          <td>${unitMatrix}</td>
          <td>${ToxStore.stockSummary(product)}<br><small>${formatProductStock(product)}</small></td>
          <td>${expired ? `<span class="danger-text">${t("expired", state.lang)}</span>` : out ? `<span class="danger-text">${t("outOfStock", state.lang)}</span>` : isLow ? `<span class="danger-text">${t("criticalWarning", state.lang)}</span>` : t("stable", state.lang)}</td>
        </tr>
      `;
    })
    .join("");
}

function ensureGlobalUi() {
  if (document.querySelector("[data-global-modal]")) return;
  const shell = document.createElement("div");
  shell.innerHTML = `
    <div class="global-toast-stack" data-global-toast-stack></div>
    <div class="global-sync-status" data-sync-status hidden></div>
    <div class="global-modal-shell hidden" data-global-modal>
      <div class="global-modal-backdrop" data-modal-close></div>
      <div class="global-modal-card">
        <div class="panel-head">
          <h2 data-modal-title>${t("deleteItem")}</h2>
        </div>
        <p class="panel-note" data-modal-text>${t("deleteConfirmText")}</p>
        <div class="toolbar modal-actions">
          <button class="button ghost" type="button" data-modal-cancel>${t("cancel")}</button>
          <button class="button primary" type="button" data-modal-confirm>${t("confirmDelete")}</button>
        </div>
      </div>
    </div>
  `;
  while (shell.firstElementChild) {
    document.body.appendChild(shell.firstElementChild);
  }
  document.querySelectorAll("[data-modal-close],[data-modal-cancel]").forEach((button) => {
    button.addEventListener("click", closeGlobalModal);
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeGlobalModal();
  });
}

let modalAction = null;

function openDeleteModal({ title, text, onConfirm }) {
  ensureGlobalUi();
  const modal = document.querySelector("[data-global-modal]");
  modal.classList.remove("hidden");
  modal.querySelector("[data-modal-title]").textContent = title;
  modal.querySelector("[data-modal-text]").textContent = text;
  modalAction = onConfirm;
  modal.querySelector("[data-modal-confirm]").onclick = () => {
    playUiSound("delete");
    try {
      modalAction?.();
    } finally {
      closeGlobalModal();
    }
  };
}

function closeGlobalModal() {
  const modal = document.querySelector("[data-global-modal]");
  if (!modal) return;
  modal.classList.add("hidden");
  modalAction = null;
}

function showNotice(message, tone = "info") {
  if (!["warning", "error"].includes(tone)) return;
  ensureGlobalUi();
  const stack = document.querySelector("[data-global-toast-stack]");
  if (!stack || !message) return;
  const toast = document.createElement("div");
  toast.className = `global-toast global-toast-${tone}`;
  toast.textContent = message;
  stack.appendChild(toast);
  setTimeout(() => {
    toast.classList.add("is-leaving");
    toast.addEventListener("transitionend", () => toast.remove(), { once: true });
  }, 2200);
}

