function navHrefMatchesCurrent(link) {
  const href = link?.getAttribute("href") || "";
  if (!href) return false;
  try {
    const target = new URL(href, window.location.href);
    const currentPath = window.location.pathname.replace(/\\/g, "/").replace(/\/+$/, "");
    const targetPath = target.pathname.replace(/\\/g, "/").replace(/\/+$/, "");
    if (currentPath !== targetPath) return false;
    const defaultHashes = {
      "sales.html": "#pos",
      "purchases.html": "#receive",
      "products.html": "#create",
      "warehouse.html": "#warehouses"
    };
    const targetFile = targetPath.split("/").pop();
    const currentHash = window.location.hash || defaultHashes[targetFile] || "";
    return !target.hash || target.hash === currentHash;
  } catch (error) {
    return false;
  }
}

function sidebarPageHref(page) {
  const [base, rawHash = ""] = String(page || "").split("#");
  const hash = rawHash ? `#${rawHash}` : "";
  const inPages = window.location.pathname.includes("/pages/");
  if (base === "index.html" || base === "../index.html") {
    return `${inPages ? "../index.html" : "index.html"}${hash}`;
  }
  return `${inPages ? base : `pages/${base}`}${hash}`;
}

function sidebarCanShow(permission) {
  try {
    if (!permission) return true;
    const user = JSON.parse(sessionStorage.getItem("tox-session-user")) || null;
    if (!user || !Array.isArray(user.permissions)) return true;
    const permissions = user?.permissions || [];
    return permissions.includes(permission) || permissions.includes("admin.settings");
  } catch (error) {
    return true;
  }
}

function setSidebarSectionOpen(section, isOpen) {
  const toggle = section?.querySelector("[data-nav-section-toggle]");
  const submenu = section?.querySelector("[data-nav-submenu]");
  if (!section || !toggle || !submenu) return;
  const hasVisibleLinks = [...submenu.querySelectorAll(".nav-link")].some((link) => !link.hidden);

  const open = Boolean(isOpen && hasVisibleLinks);
  const sectionKey = section.dataset.navSection || toggle.dataset.navSectionToggle || "section";
  sidebarOpenState.set(sectionKey, open);
  section.classList.toggle("is-open", open);
  // Keep the native hidden flag in sync with aria-hidden. A previous partial
  // permission refresh could leave this flag set and make the fly-out vanish
  // immediately even though the section state was open.
  submenu.hidden = !hasVisibleLinks;
  submenu.setAttribute("aria-hidden", String(!open));
  toggle.setAttribute("aria-expanded", String(open));
  if (document.body.classList.contains("sidebar-collapsed") && isOpen && hasVisibleLinks) {
    const rect = section.getBoundingClientRect();
    submenu.style.position = "fixed";
    submenu.style.top = `${Math.max(10, Math.min(window.innerHeight - 520, rect.top))}px`;
    submenu.style.left = `${Math.max(8, rect.left - 322)}px`;
    submenu.style.width = "310px";
    submenu.style.zIndex = "1300";
  } else {
    submenu.style.position = "";
    submenu.style.top = "";
    submenu.style.left = "";
    submenu.style.width = "";
    submenu.style.zIndex = "";
  }
  submenu.querySelectorAll(".nav-link").forEach((link) => {
    link.tabIndex = isOpen && !link.hidden ? 0 : -1;
  });
}

function syncSidebarSection(section) {
  if (!section) return;
  const toggle = section.querySelector("[data-nav-section-toggle]");
  const submenu = section.querySelector("[data-nav-submenu]");
  if (!toggle || !submenu) return;

  submenu.querySelectorAll(".nav-link").forEach((link) => {
    link.classList.toggle("active", navHrefMatchesCurrent(link));
    if (link.dataset.navPermission) link.hidden = !sidebarCanShow(link.dataset.navPermission);
  });
  const visibleLinks = [...submenu.querySelectorAll(".nav-link")].filter((link) => !link.hidden);
  const activeChild = visibleLinks.find((link) => link.classList.contains("active") || navHrefMatchesCurrent(link));
  const sectionKey = section.dataset.navSection || "section";
  const storedOpen = localStorage.getItem(`${sidebarSectionStoragePrefix}${sectionKey}`);
  const rememberedOpen = sidebarOpenState.get(sectionKey);
  const isOpen = Boolean(activeChild) || (
    rememberedOpen === undefined
      ? (storedOpen === null ? true : storedOpen !== "false")
      : rememberedOpen
  );

  section.hidden = visibleLinks.length === 0;
  submenu.hidden = visibleLinks.length === 0;
  toggle.classList.toggle("active", Boolean(activeChild));
  setSidebarSectionOpen(section, isOpen);
}

