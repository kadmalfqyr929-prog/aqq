function barcodeSvg(barcode) {
  const digits = String(barcode || "");
  const safeDigits = digits.replace(/[&<>"']/g, (char) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;"
  }[char]));
  const bits = digits
    .split("")
    .map((digit) => Number(digit || 0).toString(2).padStart(4, "0"))
    .join("");
  const width = bits.length * 2 + 20;
  let x = 10;
  const bars = bits
    .split("")
    .map((bit) => {
      const bar = bit === "1" ? `<rect x="${x}" y="6" width="2" height="44" fill="#111"/>` : "";
      x += 2;
      return bar;
    })
    .join("");
  return `<svg viewBox="0 0 ${width} 70" class="barcode-svg" xmlns="http://www.w3.org/2000/svg"><rect width="${width}" height="70" fill="#fff"/>${bars}<text x="${width / 2}" y="64" text-anchor="middle" font-size="10" fill="#111">${safeDigits}</text></svg>`;
}

